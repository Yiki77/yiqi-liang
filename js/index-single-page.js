/* ================================================================
   Single-page navigation + publication filters + sketch-grid nav
   1. Click nav item -> smooth-scroll to its section
   2. Manual scrolling -> active nav item follows the current section
   3. Publication pills filter the publication list
   4. Navbar mosaic tiles are generated by JS
   ================================================================ */

document.addEventListener("DOMContentLoaded", function () {
  const nav = document.getElementById("mainNav");
  const navLinks = Array.from(document.querySelectorAll("#mainNav .section-nav"));
  const sections = navLinks
    .map(link => document.querySelector(link.getAttribute("href")))
    .filter(Boolean);
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  function navHeight() {
    return nav ? nav.getBoundingClientRect().height : 0;
  }

  function documentTop(element) {
    return element.getBoundingClientRect().top + window.pageYOffset;
  }

  function setActive(sectionId) {
    navLinks.forEach(link => {
      link.classList.toggle("active", link.getAttribute("href") === "#" + sectionId);
    });
  }

  function scrollToSection(target, behavior) {
    const top = documentTop(target) - navHeight() + 1;
    window.scrollTo({
      top,
      behavior: behavior || (reducedMotion ? "auto" : "smooth")
    });
  }

  /* --------------------------------------------------------------
     Sketch-grid navbar
     -------------------------------------------------------------- */
  const mosaicGrid = nav ? nav.querySelector('.nav-mosaic-grid') : null;

  function buildNavMosaic() {
    if (!nav || !mosaicGrid) return;

    const width = Math.max(window.innerWidth, nav.clientWidth || 0);
    const height = Math.max(nav.offsetHeight || 76, 72);
    const cellSize = width >= 1200 ? 46 : width >= 768 ? 40 : 30;
    const cols = Math.max(12, Math.ceil(width / cellSize));
    const rows = Math.max(2, Math.ceil(height / 30));
    const total = cols * rows;

    mosaicGrid.innerHTML = "";
    mosaicGrid.style.setProperty('--mosaic-cols', cols);
    mosaicGrid.style.setProperty('--mosaic-rows', rows);

    for (let i = 0; i < total; i += 1) {
      const cell = document.createElement('span');
      cell.className = 'nav-mosaic-cell';

      const alpha = (0.10 + Math.random() * 0.18).toFixed(3);
      const blur = (5.5 + Math.random() * 5.5).toFixed(2) + 'px';
      const saturation = (0.84 + Math.random() * 0.18).toFixed(2);

      cell.style.setProperty('--mosaic-alpha', alpha);
      cell.style.setProperty('--mosaic-blur', blur);
      cell.style.setProperty('--mosaic-saturation', saturation);

      const roll = Math.random();
      if (roll > 0.84) {
        cell.classList.add('mosaic-clear');
      } else if (roll > 0.64) {
        cell.classList.add('mosaic-soft');
      }

      mosaicGrid.appendChild(cell);
    }
  }

  let mosaicResizeTimer = null;
  buildNavMosaic();

  /* Click -> smooth scroll */
  navLinks.forEach(link => {
    link.addEventListener("click", function (event) {
      const target = document.querySelector(this.getAttribute("href"));
      if (!target) return;

      event.preventDefault();
      scrollToSection(target);
      setActive(target.id);

      if (history.replaceState) {
        history.replaceState(null, "", "#" + target.id);
      }

      if (window.jQuery && jQuery("#navbarResponsive").hasClass("show")) {
        jQuery("#navbarResponsive").collapse("hide");
      }
    });
  });

  const brand = document.querySelector("#mainNav .navbar-brand");
  if (brand) {
    brand.addEventListener("click", function (event) {
      const about = document.getElementById("about");
      if (!about) return;
      event.preventDefault();
      scrollToSection(about);
      setActive("about");
      if (history.replaceState) {
        history.replaceState(null, "", "#about");
      }
    });
  }

  let ticking = false;

  function updateFromScroll() {
    const marker = window.scrollY + navHeight() + Math.min(180, window.innerHeight * 0.26);
    let current = sections[0];

    sections.forEach(section => {
      if (documentTop(section) <= marker) {
        current = section;
      }
    });

    if (window.innerHeight + window.scrollY >= document.documentElement.scrollHeight - 4) {
      current = sections[sections.length - 1] || current;
    }

    if (current) setActive(current.id);
    ticking = false;
  }

  window.addEventListener(
    "scroll",
    function () {
      if (!ticking) {
        window.requestAnimationFrame(updateFromScroll);
        ticking = true;
      }
    },
    { passive: true }
  );

  window.addEventListener("resize", function () {
    updateFromScroll();
    clearTimeout(mosaicResizeTimer);
    mosaicResizeTimer = setTimeout(buildNavMosaic, 80);
  });

  updateFromScroll();

  if (window.location.hash) {
    const target = document.querySelector(window.location.hash);
    if (target) {
      setTimeout(() => {
        scrollToSection(target, "auto");
        if (sections.includes(target)) {
          setActive(target.id);
        }
      }, 0);
    }
  }

  /* Publication filters */
  const filterButtons = Array.from(document.querySelectorAll('.publication-filter'));
  const publicationRows = Array.from(document.querySelectorAll('.publication-row'));

  function applyPublicationFilter(filter) {
    publicationRows.forEach(row => {
      const category = row.getAttribute('data-category');
      const visible = filter === 'all' || category === filter;
      row.classList.toggle('is-hidden', !visible);
    });

    filterButtons.forEach(button => {
      const isActive = button.getAttribute('data-filter') === filter;
      button.classList.toggle('active', isActive);
      button.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
  }

  filterButtons.forEach(button => {
    button.addEventListener('click', function () {
      applyPublicationFilter(this.getAttribute('data-filter'));
    });
  });

  applyPublicationFilter('all');
});
